import { describe, it, expect } from "vitest";
import ts from "typescript";
import { exportTest, presetVariable } from "./export-test";
import { checkEntry, clickEntry, createActionJournal, emulateEntry, emulateResetEntry, fillEntry } from "./action-journal";
import type { ExportTestInput, JournalTarget } from "./action-journal.types";

const diagnostics = (text: string) =>
  ts.transpileModule(text, {
    reportDiagnostics: true,
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
  }).diagnostics ?? [];

const COUPON: JournalTarget = {
  role: "textbox",
  name: "Coupon",
  label: 'textbox "Coupon"',
  locator: "getByLabel('Coupon')",
  isPassword: false,
};
const PASSWORD: JournalTarget = {
  role: "textbox",
  name: "Password",
  label: 'textbox "Password"',
  locator: "getByLabel('Password')",
  isPassword: true,
};
const APPLY: JournalTarget = {
  role: "button",
  name: "Apply",
  label: 'button "Apply"',
  locator: "getByRole('button', { name: 'Apply' })",
  isPassword: false,
};

function fixtureJournal() {
  const journal = createActionJournal();
  journal.append([
    fillEntry(COUPON, COUPON.locator!, "SAVE10"),
    fillEntry(PASSWORD, PASSWORD.locator!, "secret123"),
    clickEntry(APPLY, APPLY.locator!),
    checkEntry({ kind: "text_visible", text: "Discount: -$4.20" }, undefined)!,
  ]);
  return journal;
}

describe("export-test", () => {
  it("1. playwright: two cases, describe/test/import shape, no secret", () => {
    const journal = fixtureJournal();
    const input: ExportTestInput = {
      format: "playwright",
      suite: "Checkout coupon",
      url: "http://localhost:10040/checkout.html",
      cases: [
        {
          id: "TC-01",
          title: "Apply a valid code",
          steps: [
            { text: "Fill the form", journal: [1, 2] },
            { text: "Click Apply", journal: [3] },
            { text: "The discount is shown", journal: [4] },
          ],
        },
        {
          id: "TC-02",
          title: "Apply again",
          steps: [
            { text: "Click Apply", journal: [3] },
            { text: "The discount is shown", journal: [4] },
          ],
        },
      ],
    };
    const result = exportTest(input, journal.entries());
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(diagnostics(result.text)).toEqual([]);
    const lines = result.text.split("\n");
    expect(lines[0]).toBe("// spec: Checkout coupon — generated by tesagent");
    expect(lines[1]).toBe("import { test, expect } from '@playwright/test';");
    expect(result.text).toContain("test.describe('Checkout coupon', () => {");
    expect(result.text).toContain("  test('TC-01 Apply a valid code', async ({ page }) => {");
    expect(result.text).toContain("  test('TC-02 Apply again', async ({ page }) => {");
    expect(result.text).toContain("    await page.getByRole('button', { name: 'Apply' }).click();");
    expect(result.text).toContain("    await expect(page.getByText('Discount: -$4.20')).toBeVisible();");
    expect(result.text).toContain("process.env.TEST_PASSWORD");
    expect(result.text).not.toContain("secret123");
  });

  it("2. the step comment line comes before its journaled code", () => {
    const journal = fixtureJournal();
    const input: ExportTestInput = {
      format: "playwright",
      suite: "S",
      cases: [{ id: "TC-01", title: "T", steps: [{ text: "Fill the form", journal: [1, 2] }] }],
    };
    const result = exportTest(input, journal.entries());
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    const lines = result.text.split("\n");
    const commentIdx = lines.indexOf("    // 1. Fill the form");
    const codeIdx = lines.indexOf("    await page.getByLabel('Coupon').fill('SAVE10');");
    expect(commentIdx).toBeGreaterThanOrEqual(0);
    expect(codeIdx).toBeGreaterThan(commentIdx);
  });

  it("3. with url, page.goto follows // 1. in every case; without url, no goto", () => {
    const journal = fixtureJournal();
    const withUrl: ExportTestInput = {
      format: "playwright",
      suite: "S",
      url: "http://localhost:10040/checkout.html",
      cases: [
        { id: "TC-01", title: "A", steps: [{ text: "Fill the form", journal: [1, 2] }, { text: "Click Apply", journal: [3] }] },
        { id: "TC-02", title: "B", steps: [{ text: "Click Apply", journal: [3] }] },
      ],
    };
    const r1 = exportTest(withUrl, journal.entries());
    expect(r1.ok).toBe(true);
    if (r1.ok) {
      for (const c of withUrl.cases) {
        const lines = r1.text.split("\n");
        const idx = lines.indexOf(`    // 1. ${c.steps[0].text}`);
        expect(lines[idx + 1]).toBe("    await page.goto('http://localhost:10040/checkout.html');");
      }
    }

    const noUrl: ExportTestInput = { ...withUrl, url: undefined };
    const r2 = exportTest(noUrl, journal.entries());
    expect(r2.ok).toBe(true);
    if (r2.ok) expect(r2.text).not.toContain("page.goto");
  });

  it("4. iPhone 15 preset wraps the case in a device describe", () => {
    const journal = createActionJournal();
    journal.append([
      emulateEntry({ preset: "iPhone 15", width: 393, height: 659, scale: 3, mobile: true, touch: true }),
      clickEntry(APPLY, APPLY.locator!),
    ]);
    const input: ExportTestInput = {
      format: "playwright",
      suite: "Devices",
      cases: [{ id: "TC-01", title: "Phone", steps: [{ text: "Click Apply", journal: [2] }] }],
    };
    const result = exportTest(input, journal.entries());
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(diagnostics(result.text)).toEqual([]);
    const text = result.text;
    const iImport = text.indexOf("import { test, expect, devices } from '@playwright/test';");
    const iDescribe = text.indexOf("  test.describe('TC-01 device', () => {");
    const iDestructure = text.indexOf("    const { defaultBrowserType, ...iPhone15 } = devices['iPhone 15'];");
    const iUse = text.indexOf("    test.use(iPhone15);");
    const iTest = text.indexOf("    test('TC-01 Phone', async ({ page }) => {");
    const iClick = text.indexOf("      await page.getByRole('button', { name: 'Apply' }).click();");
    const iCloseTest = text.indexOf("    });");
    const iCloseDescribe = text.indexOf("  });");
    expect([iImport, iDescribe, iDestructure, iUse, iTest, iClick, iCloseTest, iCloseDescribe].every((i) => i >= 0)).toBe(true);
    expect(iImport).toBeLessThan(iDescribe);
    expect(iDescribe).toBeLessThan(iDestructure);
    expect(iDestructure).toBeLessThan(iUse);
    expect(iUse).toBeLessThan(iTest);
    expect(iTest).toBeLessThan(iClick);
    expect(iClick).toBeLessThan(iCloseTest);
    expect(iCloseTest).toBeLessThan(iCloseDescribe);
    expect(presetVariable("iPhone 15")).toBe("iPhone15");
    expect(presetVariable("iPad Mini landscape")).toBe("iPadMiniLandscape");
    expect(presetVariable("Desktop Chrome")).toBe("desktopChrome");
  });

  it("5. custom emulation uses a viewport test.use with no devices import", () => {
    const journal = createActionJournal();
    journal.append([
      emulateEntry({ width: 800, height: 600, scale: 2, mobile: false, touch: true }),
      clickEntry(APPLY, APPLY.locator!),
    ]);
    const input: ExportTestInput = {
      format: "playwright",
      suite: "Devices",
      cases: [{ id: "TC-01", title: "Custom", steps: [{ text: "Click Apply", journal: [2] }] }],
    };
    const result = exportTest(input, journal.entries());
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.text).toContain(
      "    test.use({ viewport: { width: 800, height: 600 }, deviceScaleFactor: 2, isMobile: false, hasTouch: true });",
    );
    expect(result.text).not.toContain("devices");
  });

  it("6. a reset before the case's first referenced entry removes the wrap", () => {
    const journal = createActionJournal();
    journal.append([
      emulateEntry({ preset: "iPhone 15", width: 393, height: 659, scale: 3, mobile: true, touch: true }),
      emulateResetEntry(),
      clickEntry(APPLY, APPLY.locator!),
    ]);
    const input: ExportTestInput = {
      format: "playwright",
      suite: "Devices",
      cases: [{ id: "TC-01", title: "After reset", steps: [{ text: "Click Apply", journal: [3] }] }],
    };
    const result = exportTest(input, journal.entries());
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.text).not.toContain("test.describe('TC-01 device'");
    expect(result.text).not.toContain("devices");
  });

  it("7. an emulate entry referenced after step 1 sets the viewport inline", () => {
    const journal = createActionJournal();
    journal.append([clickEntry(APPLY, APPLY.locator!), emulateEntry({ width: 800, height: 600, scale: 1, mobile: false, touch: false }), clickEntry(APPLY, APPLY.locator!)]);
    const input: ExportTestInput = {
      format: "playwright",
      suite: "S",
      cases: [{ id: "TC-01", title: "T", steps: [{ text: "Click", journal: [1] }, { text: "Resize and click", journal: [2, 3] }] }],
    };
    const result = exportTest(input, journal.entries());
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.text).not.toContain("test.describe('TC-01 device'");
    const lines = result.text.split("\n");
    const idx = lines.indexOf("    // 2. Resize and click");
    expect(lines[idx + 1]).toBe("    await page.setViewportSize({ width: 800, height: 600 });");
  });

  it("8. bdd default keywords: given, when, and, then", () => {
    const journal = fixtureJournal();
    const input: ExportTestInput = {
      format: "bdd",
      suite: "Checkout coupon",
      cases: [
        {
          id: "TC-01",
          title: "Apply a valid code",
          steps: [
            { text: "Open checkout" },
            { text: "Fill the form", journal: [1, 2] },
            { text: "Click Apply", journal: [3] },
            { text: "The discount is shown", journal: [4] },
          ],
        },
      ],
    };
    const result = exportTest(input, journal.entries());
    expect(result).toEqual({
      ok: true,
      text:
        "# Checkout coupon\n\n### Scenario: TC-01 Apply a valid code\n**Given** Open checkout\n**When** Fill the form\n**And** Click Apply\n**Then** The discount is shown",
    });
  });

  it("9. an explicit keyword wins over the default", () => {
    const journal = fixtureJournal();
    const input: ExportTestInput = {
      format: "bdd",
      suite: "S",
      cases: [
        {
          id: "TC-01",
          title: "T",
          steps: [{ text: "Open" }, { text: "Fill the form", journal: [1, 2], keyword: "then" }],
        },
      ],
    };
    const result = exportTest(input, journal.entries());
    expect(result.ok).toBe(true);
    if (result.ok) expect(result.text).toContain("**Then** Fill the form");
  });

  it("10. two cases each start with a blank line then ### Scenario:", () => {
    const journal = fixtureJournal();
    const input: ExportTestInput = {
      format: "bdd",
      suite: "S",
      cases: [
        { id: "TC-01", title: "A", steps: [{ text: "x" }] },
        { id: "TC-02", title: "B", steps: [{ text: "y" }] },
      ],
    };
    const result = exportTest(input, journal.entries());
    expect(result.ok).toBe(true);
    if (result.ok) {
      const lines = result.text.split("\n");
      expect(lines[1]).toBe("");
      expect(lines[2]).toBe("### Scenario: TC-01 A");
      const secondIdx = lines.indexOf("### Scenario: TC-02 B");
      expect(lines[secondIdx - 1]).toBe("");
    }
  });

  it("11. an unknown journal id is an error, in either format", () => {
    const journal = fixtureJournal();
    const input: ExportTestInput = {
      format: "playwright",
      suite: "S",
      cases: [{ id: "TC-01", title: "T", steps: [{ text: "x", journal: [9] }] }],
    };
    expect(exportTest(input, journal.entries())).toEqual({
      ok: false,
      error: "Journal entry #9 does not exist in this chat.",
    });
    expect(exportTest({ ...input, format: "bdd" }, journal.entries())).toEqual({
      ok: false,
      error: "Journal entry #9 does not exist in this chat.",
    });
  });

  it("12. the same id used in two steps and two cases appears twice per use", () => {
    const journal = fixtureJournal();
    const input: ExportTestInput = {
      format: "playwright",
      suite: "S",
      cases: [
        { id: "TC-01", title: "A", steps: [{ text: "a", journal: [3] }, { text: "b", journal: [3] }] },
        { id: "TC-02", title: "B", steps: [{ text: "c", journal: [3] }] },
      ],
    };
    const result = exportTest(input, journal.entries());
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    const count = result.text.split("await page.getByRole('button', { name: 'Apply' }).click();").length - 1;
    expect(count).toBe(3);
  });

  it("13. a line break in step text becomes a space; an apostrophe in the suite is escaped", () => {
    const journal = fixtureJournal();
    const input: ExportTestInput = {
      format: "playwright",
      suite: "It's",
      cases: [{ id: "TC-01", title: "T", steps: [{ text: "a\nb" }] }],
    };
    const result = exportTest(input, journal.entries());
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.text).toContain("    // 1. a b");
    expect(result.text).toContain("test.describe('It\\'s', () => {");
    expect(diagnostics(result.text)).toEqual([]);
  });
});
