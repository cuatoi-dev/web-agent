// 124/004 — export_test's file text, built from the chat's journal entries.
// Pure formatting; export-test-tool.ts supplies the entries.
import { quote } from "./action-journal";
import type {
  ExportCase,
  ExportKeyword,
  ExportStep,
  ExportTestInput,
  ExportTestResult,
  JournalEntry,
} from "./action-journal.types";

/** A comment or Markdown line cannot hold a line break. */
const oneLine = (s: string) => s.replace(/\r?\n/g, " ");

/** User decision 2026-09-18 (1): iPhone 15 -> iPhone15,
 *  iPad Mini landscape -> iPadMiniLandscape, Desktop Chrome -> desktopChrome. */
export function presetVariable(preset: string): string {
  const words = preset.split(/[^A-Za-z0-9]+/).filter((w) => w !== "");
  return words
    .map((w, i) => (i === 0 ? w.charAt(0).toLowerCase() + w.slice(1) : w.charAt(0).toUpperCase() + w.slice(1)))
    .join("");
}

/** The last "emulate" entry at or before the case's first referenced entry,
 *  unless an "emulate-reset" comes after it and at or before that entry. */
function caseEmulation(c: ExportCase, entries: JournalEntry[]): JournalEntry | undefined {
  const first = c.steps.flatMap((s) => s.journal ?? [])[0];
  if (first === undefined) return undefined;
  const emu = entries.filter((e) => e.kind === "emulate" && e.id <= first).pop();
  if (!emu) return undefined;
  const reset = entries.some((e) => e.kind === "emulate-reset" && e.id > emu.id && e.id <= first);
  return reset ? undefined : emu;
}

function playwright(input: ExportTestInput, byId: Map<number, JournalEntry>, entries: JournalEntry[]): string {
  const emus = input.cases.map((c) => caseEmulation(c, entries)?.emulation);
  const usesDevices = emus.some((e) => e?.preset !== undefined);
  const lines = [
    `// spec: ${oneLine(input.suite)} — generated by tesagent`,
    `import { test, expect${usesDevices ? ", devices" : ""} } from '@playwright/test';`,
    "",
    `test.describe(${quote(input.suite)}, () => {`,
  ];
  input.cases.forEach((c, i) => {
    const emu = emus[i];
    const pad = emu ? "    " : "  ";
    if (emu) {
      lines.push(`  test.describe(${quote(`${c.id} device`)}, () => {`);
      if (emu.preset !== undefined) {
        const v = presetVariable(emu.preset);
        lines.push(`    const { defaultBrowserType, ...${v} } = devices[${quote(emu.preset)}];`);
        lines.push(`    test.use(${v});`);
      } else {
        lines.push(
          `    test.use({ viewport: { width: ${emu.width}, height: ${emu.height} }, deviceScaleFactor: ${emu.scale}, isMobile: ${emu.mobile}, hasTouch: ${emu.touch} });`,
        );
      }
    }
    lines.push(`${pad}test(${quote(`${c.id} ${c.title}`)}, async ({ page }) => {`);
    c.steps.forEach((s, n) => {
      lines.push(`${pad}  // ${n + 1}. ${oneLine(s.text)}`);
      if (n === 0 && input.url) lines.push(`${pad}  await page.goto(${quote(input.url)});`);
      for (const id of s.journal ?? []) {
        const e = byId.get(id);
        if (!e) continue;
        if (e.kind === "emulate" && n > 0 && e.emulation) {
          lines.push(`${pad}  await page.setViewportSize({ width: ${e.emulation.width}, height: ${e.emulation.height} });`);
        }
        for (const code of e.code) lines.push(`${pad}  ${code}`);
      }
    });
    lines.push(`${pad}});`);
    if (emu) lines.push("  });");
  });
  lines.push("});");
  return lines.join("\n");
}

function bdd(input: ExportTestInput, byId: Map<number, JournalEntry>): string {
  const lines = [`# ${oneLine(input.suite)}`];
  const isThen = (s: ExportStep) => {
    const ids = s.journal ?? [];
    return ids.length > 0 && ids.every((id) => byId.get(id)?.kind === "check");
  };
  for (const c of input.cases) {
    lines.push("", `### Scenario: ${oneLine(`${c.id} ${c.title}`)}`);
    let whenUsed = false;
    c.steps.forEach((s, n) => {
      const fallback: ExportKeyword = n === 0 ? "given" : isThen(s) ? "then" : whenUsed ? "and" : "when";
      if (fallback === "when") whenUsed = true;
      const keyword = s.keyword ?? fallback;
      lines.push(`**${keyword.charAt(0).toUpperCase()}${keyword.slice(1)}** ${oneLine(s.text)}`);
    });
  }
  return lines.join("\n");
}

export function exportTest(input: ExportTestInput, entries: JournalEntry[]): ExportTestResult {
  const byId = new Map(entries.map((e) => [e.id, e]));
  for (const c of input.cases) {
    for (const s of c.steps) {
      for (const id of s.journal ?? []) {
        if (!byId.has(id)) return { ok: false, error: `Journal entry #${id} does not exist in this chat.` };
      }
    }
  }
  return { ok: true, text: input.format === "bdd" ? bdd(input, byId) : playwright(input, byId, entries) };
}
